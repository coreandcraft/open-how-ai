using Journey.Data;
using Journey.Data.PostgreSql;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Migrations;

namespace Journey.Tests;

public class PostgreSqlModelTests
{
    [Fact]
    public void PostgreSqlMigrationsMatchModelAndGenerateNativeSchema()
    {
        var options = new DbContextOptionsBuilder<AppDb>();
        options.UseJourneyPostgreSql("Host=localhost;Database=unused;Username=postgres");
        using var db = new AppDb(options.Options);

        Assert.False(db.Database.HasPendingModelChanges());
        var migrations = db.Database.GetMigrations().ToArray();
        Assert.Contains(migrations, name => name.EndsWith("_InitialPostgreSql"));
        Assert.DoesNotContain(migrations, name => name.EndsWith("_ExperimentalMcp"));

        var script = db.GetService<IMigrator>().GenerateScript();
        Assert.Contains("CREATE TABLE \"Users\"", script);
        Assert.Contains("timestamp with time zone", script);
        Assert.Contains("GENERATED BY DEFAULT AS IDENTITY", script);
    }
}
